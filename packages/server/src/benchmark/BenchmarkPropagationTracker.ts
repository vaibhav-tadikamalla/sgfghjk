/**
 * benchmark/BenchmarkPropagationTracker.ts
 *
 * Tracks collaborative edit propagation latency: the time from when
 * SimulatedEditor A sends a Yjs update until SimulatedEditor B applies it.
 *
 * ── How t1 and t2 are determined ─────────────────────────────────────────────
 *
 *   t1 = performance.now() in SimulatedEditor A, captured immediately BEFORE
 *        Y.Doc.transact() is called to generate the edit.
 *
 *   t2 = performance.now() in SimulatedEditor B, captured immediately AFTER
 *        Y.applyUpdate() returns when processing an incoming MSG_SYNC update.
 *
 *   latency = t2 - t1 (milliseconds)
 *
 * ── Why this is valid ─────────────────────────────────────────────────────────
 *
 *   All simulated editors run in the same Node.js event loop. performance.now()
 *   is monotonic within a process. No cross-machine clock synchronization is
 *   needed — all t1 and t2 values share the same time origin.
 *
 * ── Correlation mechanism ─────────────────────────────────────────────────────
 *
 *   Each Yjs update carries the originating clientID (a uint32 generated by
 *   Y.Doc) and a logical clock (monotonically increasing per client).
 *   Together, (clientID, clock) uniquely identifies a Yjs struct.
 *
 *   The sender records (clientID, maxClock, t1) in a pending map.
 *   The receiver extracts (clientID, clock) from the raw update binary using
 *   Y.decodeUpdate(), then looks up the matching pending entry.
 *
 * ── What this does NOT measure ────────────────────────────────────────────────
 *
 *   - Awareness / presence messages (MSG_AWARENESS = 1)
 *   - Sync step 1 / step 2 handshakes
 *   - ACK frames or JSON control messages
 *   - Server startup or benchmark scheduling delay
 *
 * ── Timeout handling ──────────────────────────────────────────────────────────
 *
 *   Pending entries older than PROPAGATION_TIMEOUT_MS are treated as timed out
 *   and removed during periodic cleanup. They are counted in `timedOutCount`.
 */

import * as Y from 'yjs';

/** Key into the pending map. */
type PendingKey = `${number}:${number}`; // `${clientId}:${clock}`

interface PendingEntry {
  key: PendingKey;
  senderEditorId: string;
  t1: number; // performance.now() at send
  enqueuedAt: number; // Date.now() for timeout tracking
}

export interface PropagationSample {
  senderEditorId: string;
  receiverEditorId: string;
  senderClientId: number;
  clock: number;
  t1: number;
  t2: number;
  latencyMs: number;
}

const PROPAGATION_TIMEOUT_MS = 10_000; // 10 seconds

export class BenchmarkPropagationTracker {
  /** Whether to record new samples (false during warm-up / cooldown). */
  private _active = false;

  private readonly pending = new Map<PendingKey, PendingEntry>();
  private readonly _samples: PropagationSample[] = [];
  private _timedOutCount = 0;
  private _errorCount = 0;

  /** Received-updates counter — including updates we could not correlate. */
  private _receivedTotal = 0;

  private cleanupTimer: ReturnType<typeof setInterval> | null = null;

  constructor() {
    // Periodic cleanup of stale pending entries
    this.cleanupTimer = setInterval(() => this.sweepTimedOut(), 2_000).unref();
  }

  // ── Lifecycle ────────────────────────────────────────────────────────────────

  activate(): void { this._active = true; }
  deactivate(): void { this._active = false; }

  dispose(): void {
    if (this.cleanupTimer) {
      clearInterval(this.cleanupTimer);
      this.cleanupTimer = null;
    }
    this.pending.clear();
  }

  // ── Recording ────────────────────────────────────────────────────────────────

  /**
   * Called by SimulatedEditor A BEFORE it applies a local transact().
   * `clock` should be the current max clock for this clientId (obtained from
   * ydoc.store.clients.get(clientId)?.length ?? 0 BEFORE the transact).
   */
  recordSend(senderEditorId: string, senderClientId: number, clock: number, t1: number): void {
    if (!this._active) return;
    const key: PendingKey = `${senderClientId}:${clock}`;
    this.pending.set(key, {
      key,
      senderEditorId,
      t1,
      enqueuedAt: Date.now(),
    });
  }

  /**
   * Called by SimulatedEditor B AFTER Y.applyUpdate() completes.
   * Extracts the sender clientID and clock from the raw Yjs update binary,
   * finds the matching pending entry, and records the latency sample.
   *
   * @param receiverEditorId - ID of the editor that received the update
   * @param update - Raw Yjs update Uint8Array
   * @param t2 - performance.now() captured immediately after applyUpdate()
   */
  recordReceive(receiverEditorId: string, update: Uint8Array, t2: number): void {
    this._receivedTotal++;
    if (!this._active) return;

    try {
      // Decode the update to extract the sender's clientID and max clock
      const decoded = Y.decodeUpdate(update);

      for (const struct of decoded.structs) {
        const clientId = struct.id.client;
        // The clock in the update is the position AFTER the update is applied.
        // We want to match the clock value just BEFORE the transaction was applied
        // on the sender side. The struct id.clock is the start of the struct.
        const clock = struct.id.clock;

        const key: PendingKey = `${clientId}:${clock}`;
        const pending = this.pending.get(key);
        if (pending) {
          this.pending.delete(key);
          const latencyMs = t2 - pending.t1;
          if (latencyMs >= 0) {
            this._samples.push({
              senderEditorId: pending.senderEditorId,
              receiverEditorId,
              senderClientId: clientId,
              clock,
              t1: pending.t1,
              t2,
              latencyMs,
            });
          }
          return; // found the primary struct, done
        }
      }
    } catch {
      this._errorCount++;
    }
  }

  // ── Sweep ────────────────────────────────────────────────────────────────────

  private sweepTimedOut(): void {
    const now = Date.now();
    for (const [key, entry] of this.pending) {
      if (now - entry.enqueuedAt > PROPAGATION_TIMEOUT_MS) {
        this.pending.delete(key);
        this._timedOutCount++;
      }
    }
  }

  // ── Accessors ────────────────────────────────────────────────────────────────

  get samples(): readonly PropagationSample[] { return this._samples; }
  get latencySamples(): number[] { return this._samples.map(s => s.latencyMs); }
  get timedOutCount(): number { return this._timedOutCount; }
  get errorCount(): number { return this._errorCount; }
  get pendingCount(): number { return this.pending.size; }
  get receivedTotal(): number { return this._receivedTotal; }

  reset(): void {
    this._samples.length = 0;
    this.pending.clear();
    this._timedOutCount = 0;
    this._errorCount = 0;
    this._receivedTotal = 0;
    this._active = false;
  }
}
